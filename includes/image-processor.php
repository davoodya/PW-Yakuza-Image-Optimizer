| Auto Orientation
|--------------------------------------------------------------------------
*/

/**
 * Apply EXIF orientation to the pixels and reset the orientation flag,
 * so the converted file always renders upright.
 *
 * @param Imagick $imagick
 * @return void
 */
function yio_auto_orient($imagick)
{
    $orientation = $imagick->getImageOrientation();

    if (
        $orientation === Imagick::ORIENTATION_UNDEFINED
        ||
        $orientation === Imagick::ORIENTATION_TOPLEFT
    ) {
        return;
    }

    switch ($orientation) {

        case Imagick::ORIENTATION_TOPRIGHT:
            $imagick->flopImage();
            break;

        case Imagick::ORIENTATION_BOTTOMRIGHT:
            $imagick->rotateImage('#000000', 180);
            break;

        case Imagick::ORIENTATION_BOTTOMLEFT:
            $imagick->flipImage();
            break;

        case Imagick::ORIENTATION_LEFTTOP:
            $imagick->transposeImage();
            break;

        case Imagick::ORIENTATION_RIGHTTOP:
            $imagick->rotateImage('#000000', 90);
            break;

        case Imagick::ORIENTATION_RIGHTBOTTOM:
            $imagick->transverseImage();
            break;

        case Imagick::ORIENTATION_LEFTBOTTOM:
            $imagick->rotateImage('#000000', 270);
            break;
    }

    $imagick->setImageOrientation(Imagick::ORIENTATION_TOPLEFT);
}

/*
|--------------------------------------------------------------------------
| Animated GIF Detection
|--------------------------------------------------------------------------
*/

/**
 * Detect animated GIFs so the pipeline can skip them instead of
 * flattening the animation into a single frame.
 *
 * @param string $file
 * @return bool
 */
function yio_is_animated_gif($file)
{
    try {

        $imagick = new Imagick($file);

        $count = $imagick->getNumberImages();

        $imagick->clear();
        $imagick->destroy();

    } catch (Throwable $e) {

        return false;

    }

    return $count > 1;
}
